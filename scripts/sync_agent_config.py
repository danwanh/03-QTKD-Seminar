#!/usr/bin/env python3
"""Generate native adapters from .agents/; --check is read-only. Python 3.11+."""
import argparse
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]


def frontmatter(text):
    """Read the scalar-only YAML subset used by this repository, not general YAML."""
    if not text.startswith("---\n"):
        raise ValueError("Missing YAML frontmatter")
    header, body = text[4:].split("\n---\n", 1)
    metadata = {}
    for line in header.splitlines():
        if not line.strip():
            continue
        key, separator, value = line.partition(":")
        if not separator or not re.fullmatch(r"[a-zA-Z_][a-zA-Z_0-9-]*", key):
            raise ValueError(f"Invalid frontmatter line: {line}")
        if key in metadata:
            raise ValueError(f"Duplicate frontmatter key: {key}")
        value = value.strip()
        if value.startswith('"') or value in {"true", "false"}:
            metadata[key] = json.loads(value)
        elif re.fullmatch(r"[a-zA-Z0-9_-]+", value):
            metadata[key] = value
        else:
            raise ValueError(f"Use a JSON-quoted string or boolean for {key}")
    return metadata, body


def expected_adapters():
    outputs = {}
    for path in sorted((ROOT / ".agents/agents").glob("*.md")):
        content = path.read_text(encoding="utf-8")
        metadata, _ = frontmatter(content)
        name = metadata["name"]
        if name != path.stem or not re.fullmatch(r"[a-z][a-z0-9-]*", name):
            raise ValueError(f"Invalid agent name: {path}")
        for folder in (".cursor/agents", ".claude/agents"):
            outputs[f"{folder}/{name}.md"] = content
        instructions = (
            f"Bạn đang làm vai {name} trong workspace QTKD TA 1–2. "
            "Trước khi làm, đọc AGENTS.md và toàn bộ .agents/rules/*.md, "
            "docs/requirements/payment-management/sources.md, rồi đọc và tuân thủ "
            f".agents/agents/{name}.md, kể cả giới hạn ghi file. "
            "Đọc docs/requirements/payment-management/spec.md làm chuẩn. "
            "Dẫn nguồn cụ thể trong TA-SPEC/TA-PDF cục bộ; bỏ qua đường dẫn "
            "tới tài liệu nghiệp vụ trực tuyến. "
            "Không tự chốt mâu thuẫn/mơ hồ/thiếu; ghi Cần xác nhận và OQ. "
            "Nếu người dùng yêu cầu kiểm tra không ghi file, chỉ trả lời trong chat."
        )
        # JSON basic strings are valid TOML basic strings for these values.
        outputs[f".codex/agents/{name}.toml"] = (
            "# Generated by scripts/sync_agent_config.py; edit .agents/ instead.\n"
            f"name = {json.dumps(name, ensure_ascii=False)}\n"
            f"description = {json.dumps(metadata['description'], ensure_ascii=False)}\n"
            f"developer_instructions = {json.dumps(instructions, ensure_ascii=False)}\n"
        )
    for path in sorted((ROOT / ".agents/rules").glob("*.md")):
        outputs[f".cursor/rules/{path.stem}.mdc"] = path.read_text(encoding="utf-8")
    return outputs


def sync(check=False):
    mismatches = []
    for relative, content in expected_adapters().items():
        path = ROOT / relative
        if path.is_file() and path.read_text(encoding="utf-8") == content:
            continue
        mismatches.append(relative)
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    if check and mismatches:
        print("FAIL: adapters missing/out of sync:\n" + "\n".join(mismatches))
        return 1
    print("PASS: adapters synchronized" if check else f"Generated/updated {len(mismatches)} adapters")
    return 0


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check only; do not write")
    args = parser.parse_args()
    try:
        sys.exit(sync(args.check))
    except (ValueError, KeyError, OSError) as error:
        print(f"FAIL: {error}", file=sys.stderr)
        sys.exit(1)
